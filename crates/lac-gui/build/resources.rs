//! The Windows resource script of `losslessaudiocut.exe`: its icon, its
//! version information and its application manifest.
//!
//! Used by `build.rs` (only when building for Windows) and, through
//! `#[path]`, by a unit test in `main.rs`, so that the script is tested on
//! every platform. Kept free of dependencies for that reason.
//!
//! Without these resources Explorer and the taskbar show the generic
//! program icon, the file's properties show no version, and Windows draws
//! the controls with the old pre-XP look and scales the window as a bitmap
//! on high-DPI screens (issue #62).

use std::path::Path;

/// `RT_MANIFEST`, the resource type of an application manifest
/// (`winuser.h`). Written as a number because the script includes no
/// headers, so that it compiles with `rc.exe` and `windres` alike.
const RT_MANIFEST: u16 = 24;

/// `CREATEPROCESS_MANIFEST_RESOURCE_ID`: the manifest of an `.exe` must
/// have this id for the loader to use it (`winuser.h`).
const CREATEPROCESS_MANIFEST_RESOURCE_ID: u16 = 1;

/// `VOS_NT_WINDOWS32` and `VFT_APP` (`verrsrc.h`): a 32/64-bit Windows
/// application.
const VOS_NT_WINDOWS32: u32 = 0x0004_0004;
const VFT_APP: u32 = 1;

/// The binary version `[major, minor, patch, 0]` of a Cargo version such
/// as `0.1.0` or `1.2.3-rc.1`. A pre-release or build suffix is dropped,
/// because the binary version holds four 16-bit numbers only; the string
/// version keeps it.
pub fn version_quad(version: &str) -> Result<[u16; 4], String> {
    let core = version.split(['-', '+']).next().unwrap_or(version);
    let parts: Vec<&str> = core.split('.').collect();
    let [major, minor, patch] = parts.as_slice() else {
        return Err(format!("version {version:?} is not MAJOR.MINOR.PATCH"));
    };
    let num = |s: &str| {
        s.parse::<u16>()
            .map_err(|_| format!("version part {s:?} of {version:?} is not a 16-bit number"))
    };
    Ok([num(major)?, num(minor)?, num(patch)?, 0])
}

/// A file name as a resource script string: backslashes doubled, since
/// `rc.exe` treats them as escapes inside quotes.
fn rc_path(path: &Path) -> String {
    path.display().to_string().replace('\\', "\\\\")
}

/// The resource script for `version` (the crate version), with the icon
/// and manifest files at `icon` and `manifest`.
///
/// The icon gets id 1, the lowest, which is the one Explorer shows.
/// The version block follows the layout of `VS_VERSIONINFO` in the Win32
/// documentation ("VERSIONINFO resource"); `040904b0` is US English with
/// the Unicode code page (1200 = 0x4b0).
pub fn rc_script(version: &str, icon: &Path, manifest: &Path) -> Result<String, String> {
    if version.contains('"') {
        return Err(format!("version {version:?} contains a quote"));
    }
    let [a, b, c, d] = version_quad(version)?;
    let icon = rc_path(icon);
    let manifest = rc_path(manifest);
    Ok(format!(
        r#"// Generated by crates/lac-gui/build.rs; see build/resources.rs.
1 ICON "{icon}"
{CREATEPROCESS_MANIFEST_RESOURCE_ID} {RT_MANIFEST} "{manifest}"

1 VERSIONINFO
FILEVERSION {a},{b},{c},{d}
PRODUCTVERSION {a},{b},{c},{d}
FILEFLAGSMASK 0x3f
FILEFLAGS 0
FILEOS {VOS_NT_WINDOWS32:#x}
FILETYPE {VFT_APP}
FILESUBTYPE 0
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "CompanyName", "losslessaudiocut"
            VALUE "FileDescription", "losslessaudiocut"
            VALUE "FileVersion", "{version}"
            VALUE "InternalName", "losslessaudiocut"
            VALUE "LegalCopyright", "GPL-3.0-or-later"
            VALUE "OriginalFilename", "losslessaudiocut.exe"
            VALUE "ProductName", "losslessaudiocut"
            VALUE "ProductVersion", "{version}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_become_four_numbers() {
        assert_eq!(version_quad("0.1.0"), Ok([0, 1, 0, 0]));
        assert_eq!(version_quad("12.345.6789"), Ok([12, 345, 6789, 0]));
        assert_eq!(version_quad("1.2.3-rc.1+build.5"), Ok([1, 2, 3, 0]));
        for bad in ["1.2", "1.2.3.4", "1.x.3", "70000.0.0", ""] {
            assert!(version_quad(bad).is_err(), "{bad:?}");
        }
    }

    #[test]
    fn script_names_the_files_and_the_version() {
        let rc = rc_script(
            "1.2.3-rc.1",
            Path::new(r"C:\src\lac\icon.ico"),
            Path::new(r"C:\src\lac\app.manifest"),
        )
        .expect("valid");
        assert!(rc.contains(r#"1 ICON "C:\\src\\lac\\icon.ico""#), "{rc}");
        assert!(rc.contains(r#"1 24 "C:\\src\\lac\\app.manifest""#), "{rc}");
        assert!(rc.contains("FILEVERSION 1,2,3,0\n"), "{rc}");
        assert!(
            rc.contains(r#"VALUE "ProductVersion", "1.2.3-rc.1""#),
            "{rc}"
        );
        assert!(rc.contains("FILEOS 0x40004\n"), "{rc}");
        // Every BEGIN has its END.
        assert_eq!(rc.matches("BEGIN").count(), rc.matches("END").count());
    }

    #[test]
    fn a_quote_in_the_version_is_refused() {
        assert!(rc_script("1.2.3-\"", Path::new("i"), Path::new("m")).is_err());
    }

    #[test]
    fn the_crate_version_and_the_resource_files_are_usable() {
        // What build.rs uses on Windows, checked on every platform.
        let packaging = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packaging");
        assert!(version_quad(env!("CARGO_PKG_VERSION")).is_ok());
        let icon = std::fs::read(packaging.join("icons/losslessaudiocut.ico")).expect("icon");
        // ICONDIR: reserved 0, type 1 (icon), then the image count.
        assert_eq!(icon.get(..4), Some(&[0, 0, 1, 0][..]));
        let manifest =
            std::fs::read_to_string(packaging.join("windows/losslessaudiocut.exe.manifest"))
                .expect("manifest");
        assert!(manifest.starts_with("<?xml"));
        for needed in [
            "Microsoft.Windows.Common-Controls",
            "PerMonitorV2",
            "asInvoker",
        ] {
            assert!(manifest.contains(needed), "{needed}");
        }
    }
}
